/* Self-hosted 360 viewer, embedded by the gallery as an iframe at /pano/?img=…
 *
 * Replaces the old cdn.pannellum.org embeds. Those took a relative panorama
 * path in the URL hash, which the viewer resolved against pannellum.org rather
 * than this site — so every panorama 404'd even before CSP blocked the frame.
 * Serving the viewer from our own origin keeps the image paths relative and
 * correct, and keeps a third-party host out of frame-src. */
(function () {
  'use strict';

  var target = document.getElementById('pano');
  var errorEl = document.getElementById('pano-error');

  function fail() {
    if (target) target.style.display = 'none';
    if (errorEl) errorEl.style.display = 'flex';
  }

  /* Only ever load our own images. This page is embeddable, so without this
   * check the `img` parameter would happily render an arbitrary remote URL
   * under this site's name. Reject anything that isn't a plain /static/ path. */
  function safePath(value) {
    if (!value) return null;
    if (!value.startsWith('/static/')) return null;
    if (value.indexOf('//') !== -1) return null;   // protocol-relative
    if (value.indexOf('\\') !== -1) return null;
    if (value.indexOf('..') !== -1) return null;   // traversal
    return value;
  }

  var img = safePath(new URLSearchParams(window.location.search).get('img'));

  if (!img || typeof window.pannellum === 'undefined') {
    fail();
    return;
  }

  /* autoLoad stays off, as it was on the old cdn.pannellum.org embeds.
   * The gallery renders every panorama twice (once as a swiper slide, once in
   * the hidden content fallback), so auto-loading five ~1.8MB equirectangular
   * images meant roughly 7MB and ten live WebGL contexts on a page that shows
   * one at a time. Click-to-load costs nothing until the reader wants it. */
  /* Small build-generated preview behind the load button, so the slide shows
   * the actual scene instead of a blank placeholder. Generated by the
   * "pano-preview" hook in eleventy.config.js. */
  var preview = '/static/images/pano-preview/' + img.split('/').pop();

  window.pannellum.viewer('pano', {
    type: 'equirectangular',
    panorama: img,
    preview: preview,
    autoLoad: false,
    showZoomCtrl: true,
    showFullscreenCtrl: true,
    hfov: 100,
    friction: 0.15,
  });
})();
